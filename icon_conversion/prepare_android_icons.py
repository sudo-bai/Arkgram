#!/usr/bin/env python3
"""Prepare Google Play and Android adaptive-icon assets from the traced artwork.

This script re-runs the JPEG cleanup stage (Gaussian smoothing + Otsu), traces
the white-detail mask with Potrace, and then emits separate assets for the two
Android surfaces:

* Google Play: 512x512, full-bleed, opaque 32-bit PNG, no baked-in rounding.
* Adaptive icon: a 108x108dp VectorDrawable containing only white details,
  with its visible bounds kept inside the central 66x66dp safe zone.

No vector coordinates are authored by hand. The Android vector reuses the
Potrace path verbatim and maps it with a group transform.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import shutil
import subprocess
import tempfile
from pathlib import Path
from xml.sax.saxutils import escape

import cv2
import numpy as np
from PIL import Image, ImageCms, ImageDraw

try:
    from vectorize_icon import Parameters, trace_mask
except ImportError:  # Allow running this file from any cwd.
    import sys

    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from vectorize_icon import Parameters, trace_mask


ADAPTIVE_VIEWPORT_DP = 108.0
SAFE_ZONE_DP = 66.0
# Keep a small antialiasing margin inside the official 66dp safe zone.
VISIBLE_TARGET_DP = 64.0
PLAY_STORE_SIZE = 512
PLAY_STORE_MAX_BYTES = 1024 * 1024


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def extract_masks(input_path: Path, params: Parameters) -> tuple[np.ndarray, np.ndarray, float]:
    gray = np.asarray(Image.open(input_path).convert("L"), dtype=np.uint8)
    smooth = cv2.GaussianBlur(gray, (0, 0), params.blur_sigma)
    threshold, binary = cv2.threshold(
        smooth, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU
    )

    dark = (binary == 0).astype(np.uint8)
    component_count, labels, stats, _ = cv2.connectedComponentsWithStats(dark, 8)
    if component_count <= 1:
        raise RuntimeError("No dark disk component found")
    largest = 1 + int(np.argmax(stats[1:, cv2.CC_STAT_AREA]))
    largest_component = (labels == largest).astype(np.uint8)
    contours, _ = cv2.findContours(
        largest_component, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE
    )
    if not contours:
        raise RuntimeError("The dark disk has no external contour")
    disk = np.zeros_like(largest_component)
    cv2.drawContours(disk, contours, -1, 1, cv2.FILLED)

    bright = ((binary == 255) & (disk > 0)).astype(np.uint8)
    count, white_labels, white_stats, _ = cv2.connectedComponentsWithStats(bright, 8)
    white = np.zeros_like(bright)
    kept: list[int] = []
    for label in range(1, count):
        area = int(white_stats[label, cv2.CC_STAT_AREA])
        if area >= params.min_feature_area:
            white[white_labels == label] = 1
            kept.append(area)
    if not kept:
        raise RuntimeError("No white details survived noise filtering")
    return disk, white, float(threshold)


def render_svg(svg_path: Path, png_path: Path, width: int, height: int) -> None:
    if shutil.which("rsvg-convert") is None:
        raise RuntimeError("rsvg-convert is required")
    subprocess.run(
        [
            "rsvg-convert",
            "-w",
            str(width),
            "-h",
            str(height),
            "-b",
            "transparent",
            str(svg_path),
            "-o",
            str(png_path),
        ],
        check=True,
        capture_output=True,
        text=True,
    )


def make_foreground_svg(white_path_data: str, transform: str, output: Path) -> None:
    svg = f'''<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="108" height="108" viewBox="0 0 108 108" preserveAspectRatio="xMidYMid meet" shape-rendering="geometricPrecision">
  <title>Arkgram adaptive foreground</title>
  <desc>White linework only; the black circular surface is supplied by the adaptive background and launcher mask.</desc>
  <g transform="{escape(transform)}" fill-rule="evenodd" clip-rule="evenodd">
    <path id="white-details" fill="#FFFFFF" d="{escape(white_path_data)}"/>
  </g>
</svg>
'''
    output.write_text(svg, encoding="utf-8")


def make_vector_drawable(mapped_path_data: str, group_attr: str, output: Path) -> None:
    attr = " ".join(group_attr.split())
    xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by icon_conversion/prepare_android_icons.py from Potrace output. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group {attr}>
        <path
            android:fillColor="#FFFFFFFF"
            android:fillType="evenOdd"
            android:pathData="{escape(mapped_path_data, {'"': '&quot;'})}" />
    </group>
</vector>
'''
    output.write_text(xml, encoding="utf-8")


def safe_bbox(alpha: np.ndarray, threshold: int = 0) -> tuple[int, int, int, int]:
    ys, xs = np.where(alpha > threshold)
    if not len(xs):
        raise RuntimeError("Rendered foreground is empty")
    return int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1


def flatten_to_opaque(icon: Image.Image, background: tuple[int, int, int]) -> Image.Image:
    rgba = icon.convert("RGBA")
    canvas = Image.new("RGBA", rgba.size, (*background, 255))
    canvas.alpha_composite(rgba)
    return canvas


def save_play_store_png(source_svg: Path, output: Path, size: int = PLAY_STORE_SIZE) -> Image.Image:
    with tempfile.TemporaryDirectory(prefix="arkgram-play-") as tmp:
        transparent = Path(tmp) / "transparent.png"
        render_svg(source_svg, transparent, size, size)
        icon = flatten_to_opaque(Image.open(transparent), (0, 0, 0))
    # Google Play asks for a 32-bit PNG. Keep RGBA, but make every pixel opaque.
    icon.putalpha(255)
    srgb = ImageCms.ImageCmsProfile(ImageCms.createProfile("sRGB")).tobytes()
    icon.save(output, format="PNG", optimize=True, icc_profile=srgb)
    return icon


def make_mask(size: int, kind: str) -> Image.Image:
    mask = Image.new("L", (size, size), 0)
    draw = ImageDraw.Draw(mask)
    if kind == "circle":
        draw.ellipse((0, 0, size - 1, size - 1), fill=255)
    elif kind == "squircle":
        radius = round(size * 0.24)
        draw.rounded_rectangle((0, 0, size - 1, size - 1), radius=radius, fill=255)
    else:
        raise ValueError(kind)
    return mask


def make_preview(foreground_1080: Image.Image, output: Path) -> None:
    size = 512
    tile = 384
    gap = 40
    margin = 50
    panels = 3
    canvas = Image.new("RGBA", (margin * 2 + tile * panels + gap * (panels - 1), 700), (31, 33, 38, 255))
    draw = ImageDraw.Draw(canvas)
    labels = ["108dp layer + safe zone", "Circular launcher mask", "Rounded-square mask"]
    fg = foreground_1080.convert("RGBA").resize((tile, tile), Image.Resampling.LANCZOS)
    for index, label in enumerate(labels):
        x = margin + index * (tile + gap)
        y = 70
        composed = Image.new("RGBA", (tile, tile), (0, 0, 0, 255))
        composed.alpha_composite(fg)
        if index == 0:
            # Show the full 108dp layer, safe-zone guide, and the icon itself.
            guide = Image.new("RGBA", (tile, tile), (0, 0, 0, 0))
            gd = ImageDraw.Draw(guide)
            inset = round(tile * (ADAPTIVE_VIEWPORT_DP - SAFE_ZONE_DP) / 2 / ADAPTIVE_VIEWPORT_DP)
            gd.rectangle((inset, inset, tile - inset - 1, tile - inset - 1), outline=(0, 220, 255, 220), width=3)
            composed.alpha_composite(guide)
        else:
            composed.putalpha(make_mask(tile, "circle" if index == 1 else "squircle"))
        canvas.alpha_composite(composed, (x, y))
        draw.text((x, 35), label, fill=(235, 238, 244, 255))
    # Small monochrome-layer explanation panel.
    canvas.save(output)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output_dir", type=Path)
    parser.add_argument("--full-svg", type=Path, default=None)
    args = parser.parse_args()

    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    full_svg = (args.full_svg or output_dir / "arkgram_icon.svg").resolve()

    params = Parameters()
    disk_mask, white_mask, threshold = extract_masks(args.input, params)
    ys, xs = np.where(white_mask > 0)
    white_bbox = (int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1)
    white_width = white_bbox[2] - white_bbox[0]
    white_height = white_bbox[3] - white_bbox[1]
    scale = min(
        VISIBLE_TARGET_DP / white_width,
        VISIBLE_TARGET_DP / white_height,
    )
    center_x = (white_bbox[0] + white_bbox[2]) / 2.0
    center_y = (white_bbox[1] + white_bbox[3]) / 2.0
    target_center = ADAPTIVE_VIEWPORT_DP / 2.0
    tx = target_center - center_x * scale
    ty = target_center - center_y * scale

    with tempfile.TemporaryDirectory(prefix="arkgram-android-") as temp_name:
        temp = Path(temp_name)
        white_svg = temp / "white.svg"
        white_path_data, source_transform = trace_mask(
            white_mask, white_svg, temp, "white", params
        )
    if not source_transform:
        raise RuntimeError("Potrace did not return its expected coordinate transform")

    # Potrace emits coordinates in a 10x, y-up coordinate system with the SVG
    # transform translate(0,2048) scale(0.1,-0.1). Compose that exact transform
    # with our safe-zone fit and centering transform.
    svg_transform = (
        f"translate({tx:.8f} {ty:.8f}) scale({scale:.8f}) "
        f"translate(0 2048) scale(0.1 -0.1)"
    )
    foreground_svg = output_dir / "arkgram_adaptive_foreground.svg"
    make_foreground_svg(white_path_data, svg_transform, foreground_svg)

    # VectorDrawable group matrices are scale then translate. For the raw
    # Potrace path this becomes scale(0.1*scale), y-flip, then a translated
    # coordinate-space offset.
    vector_scale_x = 0.1 * scale
    vector_scale_y = -0.1 * scale
    vector_translate_x = tx
    vector_translate_y = 2048.0 * scale + ty
    group_attr = (
        f'android:scaleX="{vector_scale_x:.10f}" '
        f'android:scaleY="{vector_scale_y:.10f}" '
        f'android:translateX="{vector_translate_x:.10f}" '
        f'android:translateY="{vector_translate_y:.10f}"'
    )
    foreground_vector = output_dir / "arkgram_icon_foreground.xml"
    monochrome_vector = output_dir / "arkgram_icon_monochrome.xml"
    make_vector_drawable(white_path_data, group_attr, foreground_vector)
    shutil.copyfile(foreground_vector, monochrome_vector)

    preview_1080 = output_dir / "arkgram_adaptive_foreground_1080.png"
    render_svg(foreground_svg, preview_1080, 1080, 1080)
    alpha = np.asarray(Image.open(preview_1080).convert("RGBA"))[:, :, 3]
    bbox = safe_bbox(alpha, threshold=0)
    bbox_dp = tuple(value * ADAPTIVE_VIEWPORT_DP / 1080.0 for value in bbox)

    play_png = output_dir / "arkgram_play_store_512.png"
    play_icon = save_play_store_png(full_svg, play_png)
    play_rgba = np.asarray(play_icon.convert("RGBA"))

    preview_png = output_dir / "arkgram_adaptive_preview.png"
    make_preview(Image.open(preview_1080), preview_png)

    safe_zone_px = SAFE_ZONE_DP / ADAPTIVE_VIEWPORT_DP * 1080.0
    target_zone_px = VISIBLE_TARGET_DP / ADAPTIVE_VIEWPORT_DP * 1080.0
    bbox_inside_safe_zone = (
        bbox[0] >= (1080 - safe_zone_px) / 2 - 1
        and bbox[1] >= (1080 - safe_zone_px) / 2 - 1
        and bbox[2] <= (1080 + safe_zone_px) / 2 + 1
        and bbox[3] <= (1080 + safe_zone_px) / 2 + 1
    )
    report = {
        "input": str(args.input.resolve()),
        "input_sha256": sha256(args.input),
        "parameters": {
            "blur_sigma": params.blur_sigma,
            "otsu_threshold": threshold,
            "min_feature_area": params.min_feature_area,
            "potrace_unit": params.potrace_unit,
        },
        "source_white_bbox_px": list(white_bbox),
        "source_white_size_px": [white_width, white_height],
        "adaptive": {
            "viewport_dp": ADAPTIVE_VIEWPORT_DP,
            "safe_zone_dp": SAFE_ZONE_DP,
            "visible_target_dp": VISIBLE_TARGET_DP,
            "fit_scale_source_to_dp": scale,
            "vector_group_transform": group_attr,
            "rendered_bbox_px_at_1080": list(bbox),
            "rendered_bbox_dp": [round(value, 4) for value in bbox_dp],
            "bbox_inside_66dp_safe_zone": bbox_inside_safe_zone,
            "expected_target_zone_px": [round((1080 - target_zone_px) / 2, 2), round((1080 + target_zone_px) / 2, 2)],
            "foreground_fully_transparent_outside_content": bool(alpha[0, 0] == 0 and alpha[0, -1] == 0 and alpha[-1, 0] == 0 and alpha[-1, -1] == 0),
            "background_color": "#000000",
            "foreground_layer": "white linework only; no black disk or background",
            "monochrome_layer": "same alpha mask as foreground; tinted by the system",
        },
        "play_store": {
            "size": list(play_icon.size),
            "mode": play_icon.mode,
            "bytes": play_png.stat().st_size,
            "max_bytes": PLAY_STORE_MAX_BYTES,
            "alpha_min": int(play_rgba[:, :, 3].min()),
            "alpha_max": int(play_rgba[:, :, 3].max()),
            "opaque": bool(np.all(play_rgba[:, :, 3] == 255)),
            "pre_rounded": False,
            "shadow_baked_in": False,
        },
        "outputs": {
            "play_store": str(play_png),
            "adaptive_foreground_svg": str(foreground_svg),
            "adaptive_foreground_vector": str(foreground_vector),
            "adaptive_monochrome_vector": str(monochrome_vector),
            "adaptive_preview": str(preview_png),
        },
        "sha256": {
            "play_store": sha256(play_png),
            "adaptive_foreground_svg": sha256(foreground_svg),
            "adaptive_foreground_vector": sha256(foreground_vector),
            "adaptive_monochrome_vector": sha256(monochrome_vector),
        },
    }
    report_path = output_dir / "android_icon_report.json"
    report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
